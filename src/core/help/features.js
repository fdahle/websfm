// docs/features.md: every ribbon command, where it is and what it does, made from the
// ribbon tables (ribbonTabs.js `ribbonEntries`) and the guide articles they link
// (`guide`). `npm run docs:features` writes it; features.test.js fails when the file
// no longer matches, so the list cannot fall behind the ribbon.
//
// A command says what it does with its own one-liner (`blurb`, else `tip`), or else the
// summary of the article that explains it. Commands of one group that have no one-liner
// and share an article (the camera presets, the Evaluate pages) are one row, so a
// summary is not repeated down the table.
//
// Pure: plain data in, a string out (core is pure, AGENTS.md).

import { labelText } from './ribbonTabs.js'

const HEADER = `# Features

<!-- Generated by \`npm run docs:features\` from the ribbon tables (src/core/help/ribbonTabs.js)
     and the guide (src/guide/). Do not edit by hand: a unit test fails when it is stale. -->

Every command in WebSfM's ribbon: where to find it, what it does, and the guide article
that explains it (the same text the app shows under **Other ▸ Guide**). The tabs
**Picture**, **DEM / Orthophoto** and **Reference raster** appear when an image, a
product or an imported raster is open in front.
`

const cell = (s) =>
  String(s ?? '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\|/g, '\\|')
    .trim()
const sentence = (s) => (s && !/[.!?…]$/.test(s) ? `${s}.` : s)

/** The row's notes: when a command is only available in some projects. */
function notes(cmd) {
  const out = []
  if (cmd.disabled) out.push('Coming soon.')
  if (cmd.aerialOnly) out.push('Aerial projects only.')
  return out
}

/**
 * The rows of one tab: `{ path, labels, text, guide }`, in ribbon order.
 * @param {Array<{cmd: any, tab: string, path: string}>} entries one tab's ribbon entries
 * @param {Map<string, {title: string, summary: string}>} guides article id → article
 */
export function featureRows(entries, guides) {
  const rows = []
  const shared = new Map() // `${path}\u0000${guide}` → the row commands without a one-liner join
  for (const { cmd, path } of entries) {
    const own = cmd.blurb || cmd.tip
    const article = cmd.guide ? guides.get(cmd.guide) : null
    const extra = notes(cmd)
    if (!own && extra.length === 0) {
      const key = `${path}\u0000${cmd.guide ?? ''}`
      const row = shared.get(key)
      if (row) {
        // The Scene group's Cameras toggle and Cameras size stepper read as one entry.
        if (!row.labels.includes(labelText(cmd))) row.labels.push(labelText(cmd))
        continue
      }
      // A summary the row above already gives (View ▸ Camera, then Scene) is not repeated.
      const summary = sentence(article?.summary ?? '')
      const above = rows[rows.length - 1]
      const text = above?.guide && above.guide === cmd.guide && above.text === summary ? '' : summary
      const fresh = { path, labels: [labelText(cmd)], text, guide: cmd.guide ?? null }
      shared.set(key, fresh)
      rows.push(fresh)
      continue
    }
    const text = [sentence(own || article?.summary || ''), ...extra].filter(Boolean).join(' ')
    rows.push({ path, labels: [labelText(cmd)], text, guide: cmd.guide ?? null })
  }
  return rows
}

/**
 * The whole of docs/features.md.
 * @param {Array<{cmd: any, tab: string, path: string}>} entries ribbonEntries()
 * @param {Map<string, {title: string, summary: string}>} guides article id → article
 */
export function featuresMarkdown(entries, guides) {
  const tabs = []
  for (const e of entries) {
    const last = tabs[tabs.length - 1]
    if (last?.tab === e.tab) last.entries.push(e)
    else tabs.push({ tab: e.tab, entries: [e] })
  }
  const parts = [HEADER]
  for (const { tab, entries: tabEntries } of tabs) {
    parts.push(`## ${tab}\n`, '| Where | Command | What it does | Guide |', '| --- | --- | --- | --- |')
    for (const row of featureRows(tabEntries, guides)) {
      const article = row.guide ? guides.get(row.guide) : null
      const link = article ? `[${cell(article.title)}](../src/guide/${row.guide}.md)` : ''
      parts.push(`| ${cell(row.path)} | ${cell(row.labels.join(', '))} | ${cell(row.text)} | ${link} |`)
    }
    parts.push('')
  }
  return parts.join('\n')
}
