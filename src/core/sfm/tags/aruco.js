const cache = new Map()
// A dictionary as a tag family (tagDetect.js): '4x4_50' → { NAME, WIDTH_AT_BORDER, NBITS,
// MIN_HAMMING, BIT_X, BIT_Y, CODES }. MIN_HAMMING is the smallest distance between two of
// its codes in any rotation (or a code and its own turn), worked out once.
export function arucoFamily(dict) {
  if (cache.has(dict)) return cache.get(dict)
  const m = /^([456])x\1_(50|100|250|1000)$/.exec(dict)
  if (!m) throw new Error(`Unknown ArUco dictionary ${dict}`)
  const n = Number(m[1]),
    count = Number(m[2])
  const BIT_X = [],
    BIT_Y = []
  for (let i = 0; i < n * n; i++) {
    BIT_X.push(1 + (i % n))
    BIT_Y.push(1 + Math.floor(i / n))
  }
  const fam = {
    NAME: `aruco${n}x${n}_${count}`,
    WIDTH_AT_BORDER: n + 2,
    TOTAL_WIDTH: n + 4,
    NBITS: n * n,
    // An n × n marker's black box can be mostly black: its dark blob may cover more of
    // the box than an AprilTag's ring does.
    DARK_MAX: 0.96,
    BIT_X,
    BIT_Y,
    CODES: CODES[n].slice(0, count),
  }
  fam.MIN_HAMMING = familyDistance(fam)
  cache.set(dict, fam)
  return fam
}
